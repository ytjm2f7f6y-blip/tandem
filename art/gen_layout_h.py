"""Writes plugin/Layout.h and plugin/HelpText.h from art/layout.py and art/help.py, so the
window places everything exactly where the renders put it.

    python3 art/gen_layout_h.py
"""
import os

import help as HELP
import layout as L

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "plugin", "Layout.h")

KINDS = {"large": 0, "med": 1, "small": 2, "sel": 3}
TYPES = {"knob": "Knob", "toggle": "Toggle", "fader": "Fader", "button": "Button", "lamp": "Lamp"}
MAXSTEPS = 12


def f(v):
    return f"{float(v):.4f}f"


group_names = list(L.LIT_GROUPS.keys())
group_of = {cid: gi for gi, name in enumerate(group_names) for cid in L.LIT_GROUPS[name]}


def group_rect(name):
    rects = [L.lit_rect(L.control(i)) for i in L.LIT_GROUPS[name]]
    x0, y0 = min(r[0] for r in rects), min(r[1] for r in rects)
    return x0, y0, max(r[0] + r[2] for r in rects) - x0, max(r[1] + r[3] for r in rects) - y0


def face(spec):
    inset = 9.0 if spec["w"] > 150 else 4.5
    return spec["x"] - spec["w"] / 2 + inset, spec["y"] - spec["h"] / 2 + inset, spec["w"] - 2 * inset, spec["h"] - 2 * inset


lines = []
w = lines.append
w("// Generated by art/gen_layout_h.py from art/layout.py: do not edit by hand.")
w("// Points at 100%; the art is rendered at 2x.")
w("#pragma once")
w("")
w("namespace layout {")
w("")
w(f"constexpr float W = {f(L.W)}, H = {f(L.H)};")
w(f"constexpr int kArtScale = {L.SCALE};")
w(f"constexpr float kSweep = {f(L.SWEEP)};     // continuous knobs: +-degrees")
w(f"constexpr float kKnobRadius[4] = {{{', '.join(f(L.KNOBS[k]) for k in ('large', 'med', 'small', 'sel'))}}};")
w("enum Kind { kLarge, kMed, kSmall, kSel };")
w(f"constexpr int kNumSelAngles = {len(L.SEL_ANGLES)};")
w(f"constexpr float kSelAngles[kNumSelAngles] = {{{', '.join(f(a) for a in L.SEL_ANGLES)}}};   // frames of knob_sel.png")
w("enum Type { Knob, Toggle, Fader, Button, Lamp };")
w("")
w("struct Control {")
w("    const char* id;")
w("    Type type;")
w("    int kind;           // knobs: Kind")
w("    float x, y, w, h;   // centre; w and h for buttons and lamps")
w("    int nSteps;         // selectors")
w(f"    float steps[{MAXSTEPS}];    // selector angles (degrees)")
w("    int pointer;        // pointer paint (kPointerColours), or -1 for ivory")
w("    int litGroup;       // which lit-patch image this control's lit state is cut from, or -1")
w("    float lx, ly, lw, lh;   // the patch of panel that changes when it lights")
w("    float travel;       // faders: the cap's travel, centred on y")
w("    int nPos;           // toggles: 2 or 3 positions")
w("    bool encoder;       // an endless encoder (knob_small turns all the way round)")
w("};")
w("")
cap_names = list(L.POINTER_COLOURS.keys())
w(f"constexpr int kNumPointerColours = {len(cap_names)};")
w("constexpr float kPointerColours[kNumPointerColours][3] = {" + ", ".join("{" + ", ".join(f(v) for v in L.POINTER_COLOURS[n]) + "}" for n in cap_names) + "};   // " + ", ".join(cap_names))
w(f"constexpr float kCapR = {f(L.CAP_R)};   // cap radius / knob radius")
w("")
w(f"constexpr int kNumLitGroups = {len(group_names)};   // " + ", ".join(group_names))
w("constexpr float kLitGroupRect[kNumLitGroups][4] = {" + ", ".join("{" + ", ".join(f(v) for v in group_rect(n)) + "}" for n in group_names) + "};")
w("")
w(f"constexpr float kToggleBox = {f(L.TOGGLE_BOX)}, kTogSp3 = {f(L.TOG_SP)}, kTogSp2 = {f(15.0)};")
w(f"constexpr float kFaderBoxW = {f(L.FADER_BOX[0])}, kFaderBoxH = {f(L.FADER_BOX[1])}, kFaderCapW = {f(L.FADER_CAP[0])}, kFaderCapH = {f(L.FADER_CAP[1])};")
w("")
w("inline const Control kControls[] = {")
for c in L.CONTROLS:
    t = TYPES[c["type"]]
    kind = KINDS[c["kind"]] if c["type"] == "knob" else 0
    cw, ch = c.get("w", 0), c.get("h", 0)
    if c["type"] == "lamp":
        cw = ch = 2 * c["r"]
    st = c.get("steps") or []
    steps = ", ".join(f(a) for a in (st + [0] * (MAXSTEPS - len(st)))[:MAXSTEPS])
    nsteps = len(st) if c["type"] == "knob" and c["kind"] == "sel" else 0
    cap = cap_names.index(L.POINTERS[c["id"]]) if c["id"] in L.POINTERS else -1
    gi = group_of.get(c["id"], -1)
    lr = L.lit_rect(c) if gi >= 0 else (0, 0, 0, 0)
    travel = c.get("travel", 0)
    npos = len(c["pos"]) if c["type"] == "toggle" else 0
    enc = "true" if c.get("encoder") else "false"
    w(f'    {{"{c["id"]}", {t}, {kind}, {f(c["x"])}, {f(c["y"])}, {f(cw)}, {f(ch)}, {nsteps}, {{{steps}}}, {cap}, {gi}, {", ".join(f(v) for v in lr)}, {f(travel)}, {npos}, {enc}}},')
w("};")
w("constexpr int kNumControls = int(sizeof(kControls) / sizeof(kControls[0]));")
w("")
dx, dy, dw, dh = face(L.DISPLAY)
w("// The display's glass, and the filter type window's, where the window writes.")
w(f"constexpr float kDispX = {f(dx)}, kDispY = {f(dy)}, kDispW = {f(dw)}, kDispH = {f(dh)};")
tx, ty, tw, th = face(L.TYPE_WIN)
w(f"constexpr float kTypeX = {f(tx)}, kTypeY = {f(ty)}, kTypeW = {f(tw)}, kTypeH = {f(th)};")
pt = L.PRESET_TAPE
w(f"constexpr float kPresetTapeX = {f(pt['x'])}, kPresetTapeY = {f(pt['y'])}, kPresetTapeW = {f(pt['w'])}, kPresetTapeH = {f(pt['h'])}, kPresetTapeAngle = {f(pt['angle'])};")
w("")
w("}  // namespace layout")
w("")
open(OUT, "w").write("\n".join(lines))
print("wrote", os.path.normpath(OUT))


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


ids = {c["id"] for c in L.CONTROLS} | {"f_type", "disp"}
missing = sorted(i for i in ids if i not in HELP.HELP)
if missing:
    print("no help for:", ", ".join(missing))
out = ["// Generated by art/gen_layout_h.py from art/help.py: do not edit by hand.", "#pragma once", "",
       "namespace help {", "struct Entry { const char* id; const char* name; const char* range; const char* text; };", "inline const Entry kEntries[] = {"]
for cid, (name, rng, text) in HELP.HELP.items():
    out.append(f'    {{"{cid}", "{esc(name)}", "{esc(rng)}", "{esc(text)}"}},')
out += ["};", "constexpr int kNumEntries = int(sizeof(kEntries) / sizeof(kEntries[0]));", "}  // namespace help", ""]
open(os.path.join(HERE, "..", "plugin", "HelpText.h"), "w", encoding="utf-8").write("\n".join(out))
print("wrote plugin/HelpText.h,", len(HELP.HELP), "entries")
